// Generates server/src/web_assets.zig from server/web.
// Run from the `server` directory (the Zig build step does this too).
import fs from "node:fs"
import path from "node:path"

const webDir = path.resolve("src/web")
const outFile = path.resolve("src/web_assets.zig")

const MIME = new Map([
  [".html", "text/html; charset=utf-8"],
  [".js", "text/javascript; charset=utf-8"],
  [".mjs", "text/javascript; charset=utf-8"],
  [".css", "text/css; charset=utf-8"],
  [".json", "application/json; charset=utf-8"],
  [".webmanifest", "application/manifest+json; charset=utf-8"],
  [".png", "image/png"],
  [".jpg", "image/jpeg"],
  [".jpeg", "image/jpeg"],
  [".gif", "image/gif"],
  [".webp", "image/webp"],
  [".avif", "image/avif"],
  [".svg", "image/svg+xml"],
  [".ico", "image/x-icon"],
  [".txt", "text/plain; charset=utf-8"],
  [".xml", "application/xml; charset=utf-8"],
  [".woff2", "font/woff2"],
  [".woff", "font/woff"],
])

function walk(dir) {
  if (!fs.existsSync(dir)) return []
  const out = []
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name)
    if (entry.isDirectory()) out.push(...walk(full))
    else if (entry.isFile()) out.push(full)
  }
  return out
}

function mimeFor(file) {
  return MIME.get(path.extname(file).toLowerCase()) ?? "application/octet-stream"
}

function cacheFor(urlPath) {
  if (urlPath === "/index.html") return "no-cache"
  if (urlPath.startsWith("/assets/")) return "public, max-age=31536000, immutable"
  return "public, max-age=3600"
}

const files = walk(webDir)
  .map((full) => ({
    full,
    rel: path.relative(webDir, full).split(path.sep).join("/"),
  }))
  .sort((a, b) => a.rel.localeCompare(b.rel))

const lines = [
  "// Generated by scripts/generate-web-assets.mjs. Do not edit.",
  "",
  "pub const Asset = struct {",
  "    path: []const u8,",
  "    content_type: []const u8,",
  "    cache_control: []const u8,",
  "    data: []const u8,",
  "};",
  "",
  "pub const assets = [_]Asset{",
]

if (files.length === 0) {
  lines.push(
    '    .{ .path = "/index.html", .content_type = "text/html; charset=utf-8", .cache_control = "no-cache", .data = "<!doctype html><html><body><h1>Shoufa frontend is not built</h1><p>Run <code>pnpm build</code> then rebuild shoufad.</p></body></html>" },',
  )
} else {
  for (const { full, rel } of files) {
    const urlPath = `/${rel}`
    const embed = path.relative(path.dirname(outFile), full).split(path.sep).join("/")
    lines.push(
      `    .{ .path = ${JSON.stringify(urlPath)}, .content_type = ${JSON.stringify(mimeFor(full))}, .cache_control = ${JSON.stringify(cacheFor(urlPath))}, .data = @embedFile(${JSON.stringify(embed)}) },`,
    )
  }
}

lines.push("};", "")

fs.mkdirSync(path.dirname(outFile), { recursive: true })
fs.writeFileSync(outFile, lines.join("\n"))
console.log(`generated ${outFile} with ${files.length} asset(s)`)
