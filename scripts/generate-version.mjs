// Generates server/src/version.zig from the root VERSION file.
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const root = path.resolve(fileURLToPath(new URL("..", import.meta.url)))
const versionFile = path.join(root, "VERSION")
const version = fs.readFileSync(versionFile, "utf8").trim()

if (!/^\d+\.\d+\.\d+(?:[-+][0-9A-Za-z.-]+)?$/.test(version)) {
  throw new Error(`Invalid version in ${versionFile}: ${version}`)
}

const output = path.join(root, "server", "src", "version.zig")
fs.writeFileSync(
  output,
  `// Generated by scripts/generate-version.mjs. Do not edit.\npub const version = "${version}";\n`,
)
console.log(`generated ${output} (${version})`)
